-- 正規化キーの UNIQUE 索引を落とす（ADR-0017 / 作業単位 0004b-2）。
--
-- ============================================================================
-- 1. 根拠は「作れないから」ではない。**「作られても照合が当たらないから」**
-- ============================================================================
--
-- 0002 がこの索引を張った理由（ADR-0004）は、`"aoi"` と `" aoi "` が併存すると
-- **アプリ層が `model` を trim してから照合した瞬間に両方へ一致し、
-- 書き込み先が不定になる**ことだった。担保する脅威モデルは **DB の直接編集**である。
--
-- **その脅威モデルは 0005 の CHECK では閉じていない。**
-- `PRAGMA ignore_check_constraints = ON` を立てれば、ゴースト行は今でも1行で作れる
-- （実測は tests/common/mod.rs::insert_character_ignoring_checks の doc が正）。
-- したがって「入口を塞いだから索引は要らない」とは言えない。
--
-- **言えるのは別のことである。** ADR-0017 で `CharacterName::parse` が trim をやめたので、
-- 前提だった「アプリ層が `model` を trim してから照合する」がもう成り立たない。
-- 照合は**格納値との完全一致**だけになり、ゴースト行は
--
--   * `model` の綴りとしても表現できず（`" aoi "` は `CharacterName` を作れない）、
--   * `find_character_by_name("aoi")` にも当たらず、
--   * `GET /v1/models` にも出ない
--
-- ——**どの経路からも引き当てられない。** ADR-0004 が「最も危険」とした
-- 「両方に一致して書き込み先が不定」という状態が**原理的に作れない。**
-- 存在する行は `list_characters` が「読めない行」として id で指し示す（0012b）。
--
-- ============================================================================
-- 2. 残すと害の方が大きい
-- ============================================================================
--
-- ゴースト行 `" aoi "` が1件あるだけで、この索引は**正当な識別子 `aoi` の作成を塞ぐ。**
-- 一覧にも出ず・チャットも 404・しかし作ろうとすると衝突する、という
-- ADR-0004 が潰したはずの袋小路そのものになる（実測 2026-08-16。
-- `create_character(aoi)` → `ConflictingUnnormalizedName`）。
--
-- 索引を落とせば、ゴースト行は**併存したまま無害に放置**でき、
-- 運用者は `aoi` を普通に作り直せる。**復旧の手数が減る方向にしか動かない。**
--
-- ============================================================================
-- 3. **索引と `UPDATE` / `DELETE` の `trim` は一組である**（片方だけ落とさないこと）
-- ============================================================================
--
-- `src/store/character.rs` の `UPDATE_CHARACTER` / `DELETE_CHARACTER` は、
-- ゴースト行を修復・掃除するために `WHERE trim(name, ...) = ?` で引き当てていた。
-- 「一致する行は高々1件」が成り立っていたのは**この索引が併存を防いでいたから**である。
--
-- 索引だけを落として `trim` を残すと、実測でこうなる（2026-08-16 / sqlite 3.53.4）:
--
--   rows: 1|'aoi'（本物） 2|' aoi '（ゴースト）
--   update_character("aoi") → Ok(CharacterId(2))   ← **返るのはゴーストの id**
--   rows after update = [(1,'aoi','巻き添え'), (2,' aoi ','巻き添え')]
--   delete_character("aoi") → Ok(())
--   rows after delete = []                          ← **本物ごと消えた**
--
-- **本物のキャラクターが黙って書き換わり、黙って消える。**
-- 索引が防いでいたどの事故よりも重い。したがってこの移行と同じ作業単位で
-- `trim` も外し、引き当ては**完全一致**に揃える。
--
-- 見張り番は tests/store_character.rs の
-- `an_update_or_delete_only_ever_reaches_the_row_whose_handle_matches_exactly`。
--
-- ============================================================================
-- 4. 失われるもの — ゴースト行を API から掃除する手段
-- ============================================================================
--
-- `trim` を外すと、`" aoi "` の行は `update_character` / `delete_character` からも
-- 届かなくなる（`CharacterName` に `" aoi "` を作れないため、綴りを打つ余地も無い）。
--
-- **その導線は 0004b-1 の時点で既に切れている。** 一覧はゴースト行の識別子を
-- `parse` できず `name: null` を返すので、**運用者は掃除に打つべき綴りを
-- API からは知りようがない**（実測。`{"id":1,"name":null,"invalid_columns":["name"]}`）。
-- 綴りを当てられたのはテストだけだった。
--
-- しかも `trim` が拾えたのは `TRIMMABLE` の8文字で埋まった行だけで、
-- `"Aoi"` や `"葵"` の行には最初から届かない。
-- **「識別子が読めない行の掃除手段」としては元々ごく一部しか覆っていない。**
--
-- ゴースト行を作れるのは DB を直接編集した者だけで、その者は同じ `sqlite3` で
-- 消せる。**復旧手段は `sqlite3` だけ**という整理は docs/06-roadmap.md のとおり。
--
-- ============================================================================
-- 5. `name` の UNIQUE は残る
-- ============================================================================
--
-- 落とすのは式索引だけ。`character.name` の列制約 `UNIQUE`（0005 で作り直した表の
-- 宣言に含まれる。実体は sqlite_autoindex_character_1）はそのまま残るので、
-- **完全一致で同名が2行できることはない**し、`WHERE name = ?` の走査も索引に乗る。
--
-- 見張り番は tests/store_schema.rs の `character_name_must_be_unique` と
-- `migration_creates_every_declared_index`（宣言した索引の一覧から1本減る）。

DROP INDEX character_name_key_idx;
