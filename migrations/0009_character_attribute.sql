-- キャラクターの不変属性（キー付き）を置くテーブル（ADR-0009 / 作業単位 12a）。
--
-- 「一人称: 僕」「種族: 猫獣人」のような**変わりようのない要素**の置き場。
-- 動機と、なぜ散文（base_persona）では足りないのかは ADR-0009 にある。**ここには写さない。**
--
-- ============================================================================
-- 名前に memory を含めない
-- ============================================================================
--
-- `memory` の SQL 走査テスト（src/store/memory.rs の no_statement_updates_or_deletes_a_memory）は
-- **テーブル名の文字列**で走査する。名前に memory を含むテーブルを作ると、
-- そこへの UPDATE / DELETE が「記憶を潰す文」として誤検出されるか、
-- 逆に走査の語が広がって誤放免される。ADR-0009 の「実装上の注意」。
--
-- ============================================================================
-- subject を持たせる
-- ============================================================================
--
-- `memory.subject` と同じ 2 値。「年齢: 19」がキャラのものか利用者のものかを落とすと
-- モデルは取り違える（CLAUDE.md 絶対制約と同じ理由が属性にも効く / ADR-0009）。
-- 綴りは memory と揃える（src/store/memory.rs の subject_to_db が両方の唯一の写し元）。
--
-- ============================================================================
-- 主キーを (character_id, subject, key) にする理由
-- ============================================================================
--
-- **subject を外すと「利用者の年齢」と「キャラクターの年齢」が併存できない。**
-- 分けた意味がそこで消える。逆に key だけを一意にしないと、同じ主語に
-- 「一人称」が 2 行入り、どちらがプロンプトに載るかが挿入順まかせになる。
--
-- この主キーは自動索引（sqlite_autoindex_character_attribute_1）を作り、
-- 先頭列が character_id なので「そのキャラクターの属性を引く」読みはそれで足りる。
-- **明示的な索引は足さない**（tests/store_schema.rs の EXPECTED_INDEXES に写しが増える）。
--
-- ============================================================================
-- 上限は 12 文字 / 20 文字。**アプリ層と二重に持つ**
-- ============================================================================
--
-- 数字の出どころは ADR-0009（2026-08-20 の追記）。**ここには写さない。**
-- domain::AttributeKey::MAX_CHARS / AttributeValue::MAX_CHARS と対になっているが、
-- **適用済みのマイグレーションは編集できない**ので、この 12 / 20 は今後もこの値のまま。
-- 2 つは独立した定数で、揃っていることは tests/store_schema.rs が見張る
-- （attribute_limits_match_the_schema_check）。
-- **上げる方向はいつでも新しい 000N_*.sql で緩められるが、下げる方向は取れない**
-- （保存済みの行が読めなくなる。AttributeKey::MAX_CHARS の doc）。
--
-- ============================================================================
-- TEXT 列でも typeof を縛る（stat_alloc.value の罠の TEXT 版）
-- ============================================================================
--
-- stat_alloc.value のコメントは「INTEGER 宣言の列に '3' を入れるとアフィニティ変換で
-- 通る」と書いている。TEXT 列では**向きが逆**になり、次のことが起きる（実測 /
-- 2026-08-20 / sqlite3 3.53.4）:
--
--   受理: 'abc' / 19（TEXT アフィニティで '19' へ変換されてから CHECK を通る）
--   拒否: x'00'（BLOB は TEXT アフィニティで変換されない）
--
-- **BLOB は length() がバイト数を返し、trim() の空白判定も別物になる**ので、
-- typeof を縛らないと「読み出しでだけ落ちる行」が作れる
-- （try_get::<String> が ColumnDecode になり、原因が SQL 側に見える）。
--
-- ============================================================================
-- 埋め込み NUL を弾く（length() の CHECK だけでは足りない）
-- ============================================================================
--
-- SQLite の length() は**テキストを最初の NUL までしか数えない。** 実測（同日 / 同版）:
--
--   'ab' || char(0) || 'cdefghij'  →  length = 2 / 実バイト数 = 11
--
-- つまり `length(key) <= 12` だけでは、NUL を混ぜた任意長の値が通る。
-- character.handle は `length(cast(handle AS BLOB)) = length(handle)` で潰しているが、
-- **その形はここでは使えない**（日本語は 1 文字 3 バイトなので正当な値まで落ちる）。
-- NUL そのものを instr で見る。
CREATE TABLE character_attribute (
    character_id INTEGER NOT NULL REFERENCES character(id) ON DELETE CASCADE,
    subject TEXT NOT NULL CHECK (subject IN ('user', 'character')),
    -- 空白の扱いは stat_alloc.axis と同じ（半角スペースだけでは足りない理由もそちら）。
    -- 空のキーを許すと、プロンプトに**キーのない「: 猫獣人」**が載る。
    key TEXT NOT NULL CHECK (
        typeof(key) = 'text'
        AND instr(key, char(0)) = 0
        AND length(trim(
            key,
            ' ' || char(9) || char(10) || char(11) || char(12) || char(13) || char(12288) || char(160)
        )) > 0
        AND length(key) <= 12
    ),
    -- **空の値は行ごと落とす**（ADR-0009）。`種族: ` と書くとモデルが欠落を演技する。
    -- 「性格値 0 の軸」と同じ扱いにはしない——あちらは 0 が正当な保存値で、
    -- 落とすのは prompt 層の責務だが、**空文字はそもそも保存させない。**
    value TEXT NOT NULL CHECK (
        typeof(value) = 'text'
        AND instr(value, char(0)) = 0
        AND length(trim(
            value,
            ' ' || char(9) || char(10) || char(11) || char(12) || char(13) || char(12288) || char(160)
        )) > 0
        AND length(value) <= 20
    ),
    PRIMARY KEY (character_id, subject, key)
);
