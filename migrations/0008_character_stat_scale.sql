-- character に stat_scale（性格ステータスの尺度）を足す（ADR-0015 / 作業単位 0011a-1）。
--
-- 本番のプロンプトは性格ステータスの尺度を一切載せておらず、`STAT_NOTE` は
-- 「数値が大きいほどその傾向が強く出ます。」とだけ言って**範囲を言わない**。
-- ADR-0012 の実測は「尺度を伝えると数値が意味を持つ」と言っているので、
-- その尺度をキャラクターごとの列として持つ。**プロンプトへ載せるのは 0011b。**
--
-- 既定値 10 / 上限 100 / 下限 1 の根拠は ADR-0015（2026-08-19 の追記）にある。
-- **ここには写さない**（写すと ADR を訂正したときにこちらだけ黙って古びる）。
--
-- ============================================================================
-- DEFAULT が CHECK を満たしている必要がある（0004 の実測を引き継ぐ）
-- ============================================================================
--
-- SQLite の ALTER TABLE ADD COLUMN は CHECK 制約を付けられるが、
-- **DEFAULT 値がその CHECK を満たしていなければ ADD COLUMN 自体が失敗する**
-- （migrations/0004_character_display_name.sql の実測）。
-- 危ないのは「空の開発用 DB では通り、行のある本番 DB でだけ落ちる」形なので、
-- **既存行のある DB で実際に当てて確認した**（2026-08-19 / sqlite3 3.53.4）:
--
--   既存行5件 + `NOT NULL DEFAULT 10 CHECK (… BETWEEN 1 AND 100)` → **成功**
--   （全行が stat_scale = 10 で埋まった）
--
-- 10 は CHECK を満たすので通る。0 や 101 を DEFAULT にすると落ちる。
--
-- ============================================================================
-- typeof を縛る理由（stat_alloc.value と同じ）
-- ============================================================================
--
-- SQLite の型アフィニティ対策。INTEGER 宣言の列でも `'abc'` は数値化できず
-- TEXT のまま格納され、比較規則上 TEXT > INTEGER なので `BETWEEN 1 AND 100` が
-- 素通りする。実測（2026-08-19 / sqlite3 3.53.4 / 既存行のある DB）:
--
--   拒否: 0 / 101 / -1 / 'abc' / '3abc' / '３' / 2.5
--   受理: 1 / 100 / '3' / 3.0   ← 後ろ2つはアフィニティ変換で整数 3 になってから通る
--
-- **つまりアプリ層の入力検証を省いてよい理由にはならない**
-- （0001 の stat_alloc.value のコメントと同じ結論）。検証は domain::StatScale が持つ。

-- ★ **下の `DEFAULT 10` は「移行した時点の既定」であって、`StatScale::DEFAULT` の写しではない。**
--   適用済みのマイグレーションは1文字も編集できない（チェックサムが変わると
--   その DB は起動不能になる / CLAUDE.md 2節）ので、**この 10 は今後も 10 のまま。**
--   `domain::StatScale::DEFAULT` を別の値に変えても、ここは変えない——変えられない。
--   つまり2つの 10 は**独立した別の定数**で、揃っているのは偶然ではなく
--   「この移行を当てた日にたまたま一致していた」というだけの関係にすぎない。
--   （新しい既定を既存行へ配りたくなったら、そのときに新しい `000N_*.sql` を足すこと。）

ALTER TABLE character ADD COLUMN stat_scale INTEGER NOT NULL DEFAULT 10
    CHECK (typeof(stat_scale) = 'integer' AND stat_scale BETWEEN 1 AND 100);

-- 既存行の尺度を、実際に使われている最大値まで引き上げる。**この1文が移行の本体。**
--
-- 落とすと、既定の 10 のまま残った既存キャラクターは、
-- **値を尺度に従わせた瞬間（0011a-2）に読めなくなる。** `stat_alloc.value` は
-- 現在 `u32` で上限が無いので、11 以上の値を持つ行は実際に作れる。
--
-- min(100, …) は SQLite の2引数スカラー関数（集約の min とは別物）。
-- 実測（2026-08-19 / sqlite3 3.53.4）——既存行5件に当てた結果:
--
--   最大値 5   の行 → 10   （WHERE に当たらないので DEFAULT のまま）
--   最大値 42  の行 → 42
--   最大値 150 の行 → 100  （上限で頭打ち。下記のとおり救えていない）
--   軸が1件も無い行 → 10   （WHERE の EXISTS が偽）
--   最大値 10  の行 → 10   （`value > 10` に当たらない）
--
-- **サブクエリが NULL を返す経路は無い。** WHERE の EXISTS が
-- 「その character_id の stat_alloc が1行以上ある」ことを保証しているので、
-- 同じ相関条件の max(value) は必ず値を返す（上の「軸が1件も無い行」がその確認）。
--
-- ★ **value > 100 の行はこの手では救えない。** 尺度の上限が 100 なので、
--   150 のような値を持つ行は尺度を 100 までしか上げられず、
--   0011a-2 で値を尺度に従わせた時点でその行は読めなくなる。
--   **「起こらない」ではない**——value は u32 で上限が無く、
--   /admin/ の PUT .../stats から 4294967295 まで書ける。
--   該当する DB は、sqlite3 で value 側を 100 以下へ直すか、その軸を消すこと。
UPDATE character SET stat_scale = min(100, (SELECT max(value) FROM stat_alloc WHERE character_id = character.id))
 WHERE EXISTS (SELECT 1 FROM stat_alloc WHERE character_id = character.id AND value > 10);
