//! ログの**行**と**欄**を突き合わせる道具。**`src/` と `tests/` が同じ1本を読む**
//! （作業単位 B-2 / B-2-2 で `src/` に一本化し、B-3a で `tests/` を畳んだ）。
//!
//! # このファイルは2つのクレートにコンパイルされる
//!
//! | 読む側 | 経路 |
//! |---|---|
//! | `src/**` の単体テスト | [`crate::testlog`] の `mod assert;` |
//! | `tests/**` の統合テスト | `tests/common/mod.rs` の `#[path = "../../src/testlog/assert.rs"]` |
//!
//! **写しではなく同じ文字列**なので、ここを緩めれば両方が一緒に緩む。
//! だから押さえの見張り番も1組でよい ——[`crate::testlog`] の `mod tests` に置いてある。
//! **期待値はこの関数を通さないべた書き**なので、緩めれば必ず赤くなる
//! （CLAUDE.md「写しを1つにしても、その1つは自動的には守られない」）。
//!
//! # 本番コードからは呼べない
//!
//! **`testing` フィーチャの下に出していない。** 出すと
//! `cargo test` / `cargo clippy --all-targets` は dev-dependency の自己参照で
//! `testing` を有効にするため、**本番コードがここを呼んでも両方が通る**
//! （CLAUDE.md 2節。素の `cargo build` だけが検出できる）。
//!
//! ここは**どのフィーチャでもライブラリの外に出ない。**
//! 親の [`crate::testlog`] が `#[cfg(test)]` なので、本番ビルドでは
//! **このファイルはコンパイルすらされない**（＝呼びようがない）。
//! 見張り番は `the_testlog_module_is_never_exposed_by_a_feature`
//! （[`crate::testlog`] の `mod tests`）——`src/lib.rs` の宣言そのものを読み、
//! フィーチャで開ける形に変わったら落ちる。
//!
//! # ここで `crate::` を参照しないこと
//!
//! `#[path]` で統合テストのクレートにも取り込まれるので、そこでの `crate` は
//! **`personacore` ではなくそのテストバイナリ**を指す。
//! **`personacore` の中身に依存するものを置かない**こと
//! （`std` と、両方のクレートから見える外部クレート —— `tracing` /
//! `tracing_subscriber` —— までは使ってよい）。
//! doc コメントのリンクは解決できなくても警告にならないので、経路の説明には使ってよい。
//!
//! # ここに何が入っているか（作業単位 B-3 で2つ目が増えた）
//!
//! | もの | 何のため |
//! |---|---|
//! | [`line_containing`] / [`line_with_field`] | ログの**行**を選ぶ（B-2 / **B-21b**） |
//! | [`has_field`] / [`bracketed_field`] / [`has_key`] / [`quoted_field`] | ログの**欄**を突き合わせる（B-2-2 / B-12b / **B-21d** / **B-32**） |
//! | [`SharedBuffer`] / [`install_global_log`] | ログを**溜める器**と、その差し込み（B-3） |
//!
//! **⚠ 行を選ぶ道具が2つあるのは、選び方が2種類あるから**（B-21b）——
//! **地の文（`tracing` のメッセージ）で選ぶ**なら [`line_containing`]、
//! **欄（`キー=値`）で選ぶ**なら [`line_with_field`]。**混ぜないこと。**
//!
//! **⚠ ファイルを増やして分ける形は採らない。** `tests/common/mod.rs` の `#[path]` を
//! 2本にすると、**見張り番が見ているのは1本だけ**なので、
//! 増やした方は黙って写しへ向け替えられる（B-12 の判断）。**この1本に集める。**

/// 手掛かりを含む**行を1本**取り出す。**無ければ落とす。**
///
/// # 手掛かりが**欄**（`キー=値`）なら、こちらではなく [`line_with_field`]（作業単位 B-21b）
///
/// ここは**素の部分一致**なので、欄を手掛かりに渡すと
/// **キーの側が伸びた別の欄**（`x_…=…`）や**値の側が伸びた別の値**（`…=…_x`）を持つ行を掴む。
/// **どちらも「欄の値を取り違える変異」がまさに作る形**（[`has_field`] の doc の表）。
///
/// **⚠ 行を選ぶのも主張の一種である**——**どの行を読むかを決めているのは手掛かり**なので、
/// 手掛かりが緩ければ、その後の assert がどれだけ厳しくても**別の行に対して**成立しうる。
///
/// **ここが素の部分一致でよいのは、手掛かりが `tracing` のメッセージそのもの**
/// （`キー=` の形をしていない）**のときだけ。** メッセージには伸びるキーが無い。
///
/// # なぜ `output.contains(..)` で済ませないのか（作業単位 24-2 / B-1-2 / B-2）
///
/// 捕捉した出力は**複数のイベントが並んだ文字列**である。
/// 深刻度（`WARN`）や欄（`session_id=1`）を出力全体に対して `contains` で見ると、
/// **その深刻度・その欄が、主張したいイベントのものかを一切見ていない。**
/// **「その行が出た」と「その行がこう言っている」は別の主張である。**
///
/// 実測で2回、別々の形で通り抜けている:
///
/// | 作業単位 | 変異 | 旧い形（出力全体を見る） |
/// |---|---|---|
/// | 24-2 | 申告なしの記録を `warn` → `info` | **緑**（無関係の行の `WARN` を拾う） |
/// | B-1-2 | 記録の `session_id` を `character_id` へ | **緑**（別の行の `session_id=1` を拾う） |
///
/// CLAUDE.md「**抜けるのはいつも帰属**——載っているかではなく、どれのものか」。
///
/// # 統合テストでは、**混ざる相手が別のテスト**になる
///
/// `tests/**` はグローバルの subscriber を差すので、同じバッファに
/// **並行して走る他のテストの行**が入る（実測: `context_tokens=16384` は
/// `the_prompt_budget_comes_from_the_configuration` の起動ログにも載る）。
/// 危険の中身は違うが、**打つ手は同じ**——値の主張は必ず同じ行の中で行う。
///
/// # 一本化しただけでは守られない
///
/// **呼び出し側は全員この関数で観測対象を作る**ので、ここが緩めば
/// （例: 行に切らず出力をそのまま返す）**呼び出し側は全部緑のまま**になる
/// （CLAUDE.md「写しを1つにしても、その1つは自動的には守られない」）。
/// **この関数の外にある値で押さえる見張り番**が [`crate::testlog`] にある——
/// 期待値は関数を通さない**べた書きの行**なので、緩めれば必ず赤くなる。
pub(crate) fn line_containing<'a>(output: &'a str, marker: &str) -> &'a str {
    output
        .lines()
        .find(|line| line.contains(marker))
        .unwrap_or_else(|| panic!("{marker:?} を含む行があること: {output:?}"))
}

/// `キー=値` が**空白区切りのトークンとして丸ごと**在るか（作業単位 B-2-2）。
///
/// # なぜ `contains(field)` で済ませないのか
///
/// **桁や接尾辞が伸びただけの別の値に当たる。**
///
/// | 探すもの | `contains` が当たってしまう別の値 | 起きること |
/// |---|---|---|
/// | `件数=1` | `件数=10` | **10 倍の回**を「1 件だった」と読む |
/// | `結末=structured` | `結末=structured_nested` | **別の結末**を同じものと読む |
/// | `session_id=1` | `x_session_id=1` | **キーの側が別物**なのに当たる |
///
/// どれも「欄の値を取り違える変異」がまさに作る形なので、
/// **トークンとして完全一致**させる。
///
/// **⚠ ここに実際の欄名（接頭辞つきの綴り）を書かないこと。**
/// `server::drift` の走査（欄名が他のモジュールに現れたら落ちる）に当たる
/// ——**着手時に実際に赤くした**（CLAUDE.md「走査系のテストが増えると、
/// 互いのフィクスチャで誤爆する」）。**このファイルも走査対象の `src/**` にある。**
///
/// # 否定（「無い」の主張）に、この関数を使ってよいか（作業単位 B-21）
///
/// **言いたいことで3つに分かれる**（3行目は作業単位 B-21d で足した）。
/// **この表がこの3つの使い分けの権威。呼び出し側に書き写さないこと。**
///
/// | 言いたいこと | 使うもの | 理由 |
/// |---|---|---|
/// | **そのキーの値が、この特定の値ではない** | **この関数** | 素の `contains` は**キーが伸びた別の欄**を掴んで**誤って赤くする** |
/// | **そのキーが、値によらず一切現れない** | [`has_key`] | ここは**完全なトークン一致**なので値が要る。**`キー=` だけでは何とも比べられない** |
/// | **その文言・その本文が一切現れない**（`キー=` の形ではない） | **素の `contains`** | 伸びるキーが無いので、素の部分一致がいちばん強い |
///
/// **⚠ 2行目は、B-21 では「素の `contains`」と書いてあった。**
/// **B-21d のレビューが、それでは足りない実例を実測した**——
/// `!has_field(&output, "extracted=0")` と書いた見張り番は、
/// **`extracted=1` が載っても黙る**（値が違うので主張は成立してしまう）。
/// **素の `contains("extracted=")` へ替えるのは逆向きに壊れる**（`x_extracted=` を掴む）。
/// **だから3つ目の道具を足した。** 経緯は [`has_key`] の doc。
///
/// **⚠ 1行目は抽象論ではない。実際に起きた。**
/// 作業単位 E-2 が `checked_sub_model=` という欄を1本足した瞬間、
/// `tests/server_context_refresh.rs` の否定側 `!line.contains("sub_model=…")` が
/// **その囮を掴んで赤くなった**——**実装は正しいのにテストだけが落ちる形。**
/// **E-2 は欄名を改名して回避した**（いまの `checked_main` / `checked_sub`）。
///
/// **B-21 で呼び出し側を `!has_field(..)` へ寄せて根治した。実測してある**
/// （2026-08-28 / **同じ囮を足す変異**: 着手前は **1 赤**、着手後は **1687 全緑**）。
///
/// **⚠ 締まりが緩むのではない。** `sub_model=` の値が**1文字でも伸びた綴り**は
/// 「サブ側が本文モデルを引いた」ではなく「**別物を引いた**」なので、
/// **この関数が返す `false` の方が、主張として正しい。**
///
/// **⚠ ここに書いた綴りは、上の警告には当たらない。** 上が禁じているのは
/// `server::drift` の接頭辞つきの欄名（あちらの `DRIFT_FIELDS`）で、
/// この綴りはその一覧に無い（B-21 で確認し、走査を回して裏を取った）。
///
/// # 一本化しただけでは守られない
///
/// [`line_containing`] と同じ穴がある——**呼び出し側は全員この関数で欄を確かめる**ので、
/// ここが `contains` に緩めば**呼び出し側の判定も一緒に緩み、全部緑のまま**になる
/// （CLAUDE.md「写しを1つにしても、その1つは自動的には守られない」）。
/// **この関数の外にある値で押さえる見張り番**が [`crate::testlog`] にある
/// ——期待値は関数を通さない**べた書きの文字列**なので、緩めれば必ず赤くなる。
///
/// # 主張の本体には**行**を渡すこと
///
/// `split_whitespace` は**改行もまたぐ**ので、出力全体を渡すと
/// 「その欄がどの行のものか」を見ないことになる（[`line_containing`] の doc）。
/// 「その欄がどこかに載っている」だけを言う**前提**の assert では
/// 出力全体を渡してよいが、**主張の本体は必ず行に切ってから渡す。**
pub(crate) fn has_field(line: &str, field: &str) -> bool {
    line.split_whitespace().any(|token| token == field)
}

/// **その名前の欄が、値によらず在るか**（作業単位 B-21d）。
///
/// 否定（`!has_key(..)`）で使うために足した3つ目の道具。
/// **使い分けの権威は [`has_field`] の doc の表。ここに書き写さないこと。**
///
/// # なぜ [`has_field`] では務まらないのか
///
/// あちらは**完全なトークン一致**なので、**値を1つ名指しすることしかできない。**
/// 「その欄を出さないこと」を `!has_field(.., "キー=0")` と書くと、
/// **値が `0` 以外なら黙る。**
///
/// **実測**（B-21d のレビュー / 2026-08-29）——`server::extract` の
/// 「走らなかった回に件数の欄を出さないこと」という見張り番に対して、
/// **`record_skip` の枝へ `extracted = 1,` を1本足す変異が全緑を通った。**
/// **文面は「欄を出さないこと」と言い、実装は「値が 0 ではないこと」しか見ていなかった。**
/// 実害は ADR-0021 §7 そのもの——**破棄率の分母に「走っていない回」が混ざる。**
///
/// # なぜ素の `contains("キー=")` では務まらないのか
///
/// **キーの側が伸びた別の欄を掴んで、実装が正しいのに落ちる。**
/// [`has_field`] の doc が E-2 の実例を挙げている
/// （`checked_sub_model=` を1本足しただけで `!contains("sub_model=…")` が赤くなった）。
///
/// ここは**トークンの先頭から**見るので、`x_キー=` には当たらない。
///
/// # 値は一切見ない
///
/// **`キー=` で始まるトークンが1つでもあれば `true`。**
/// 値まで言いたいなら [`has_field`]、値に空白が入るなら
/// [`bracketed_field`]（`キー=[…]`）か [`quoted_field`]（`キー="…"`）。
///
/// # 一本化しただけでは守られない
///
/// [`has_field`] と同じ穴がある——ここが `contains` に緩めば呼び出し側も一緒に緩む。
/// **この関数の外にある値で押さえる見張り番**が [`crate::testlog`] にあり、
/// 入力も期待値も**関数を通さないべた書き**にしてある。
pub(crate) fn has_key(line: &str, key: &str) -> bool {
    let prefix = format!("{key}=");
    line.split_whitespace()
        .any(|token| token.starts_with(&prefix))
}

/// **欄**（`キー=値`）を**トークンとして丸ごと**持つ行を1本取り出す。**無ければ落とす。**
///
/// [`line_containing`] の**欄版**（作業単位 B-21b）。判定は [`has_field`] に預けてある
/// ——**同じ受理集合で選び、同じ受理集合で主張する。**
///
/// # なぜ [`line_containing`] で選んではいけないのか
///
/// **行を選ぶのも主張の一種である**（「**どの行を読むか**」）。
/// あちらは素の部分一致なので、欄を手掛かりに渡すと**別の欄を持つ行**を掴む:
///
/// | 探すもの | あちらが掴んでしまう行 | 起きること |
/// |---|---|---|
/// | `結末=structured` | `x_結末=structured` を持つ行 | **キーの側が別物**なのに、その行で全部の主張が成立する |
/// | `結末=structured` | `結末=structured_x` を持つ行 | **別の結末**の行を読んで、その行で全部の主張が成立する |
///
/// **⚠ 「選び終えた行に [`has_field`] を当てる」書き方との差は、条件つきである。**
/// **候補が1本しか無いなら、どちらでも赤になる**（B-21b で実測した変異は全部この形だった）。
/// **差が出るのは、伸びた欄を持つ行と正しい行が同時に在るとき**
/// ——あちらは先に見つけた方を返すので、**間違った行を掴んだまま主張が成立しうる。**
/// **選ぶ側と主張する側の受理集合を揃えておけば、その場合分けが要らない。**
///
/// # 使い分け（**混ぜないこと**）
///
/// | 手掛かり | 使うもの |
/// |---|---|
/// | **欄**（`キー=値`） | **この関数** |
/// | **`tracing` のメッセージ**（地の文の断片） | [`line_containing`]（伸びるキーが無い） |
///
/// # 同じ欄を持つ行が複数あれば、**最初の1本**を返す（B-21b のレビュー指摘）
///
/// **`lines()` を先頭から探し、最初に見つかった行を返す。**
/// **⚠ 呼び出し側は現に一意性へ寄りかかっている** ——
/// `tests/server_chat_parse_log.rs` の `LogSection` は**区間が伸びる**仕掛けなので、
/// 同じラベルの行が2本入りうる。**だから向きを未規定のままにしない。**
///
/// **⚠ これは「そう書いた」ではなく「そう見張っている」。**
/// 押さえの植えたソースは**同じ欄を持つ行を2本**持ち、期待値は**先に出た方**なので、
/// **後ろから探す変異（`.rev()`）も、末尾を返す変異も赤になる。**
///
/// **レビューが穴を実測している**（2026-08-28）——2本目が無かった版では
/// `.rev()` が **1712 passed / 1 failed** で通り、**唯一の赤は写し検出の文字列走査**だった。
/// **文字列走査は振る舞いの権威ではない**（断片を書き直しながら向きを変えれば黙る）。
///
/// # 一本化しただけでは守られない
///
/// [`line_containing`] と同じ穴がある——**呼び出し側は全員この関数で観測対象を作る**ので、
/// ここが緩めば（例: [`has_field`] ではなく `contains` で探す）**呼び出し側は全部緑のまま**になる。
/// **この関数の外にある値で押さえる見張り番**が [`crate::testlog`] にある
/// ——**囮を持つ植えたソース**（探す欄の、キーが伸びた行と値が伸びた行を**先に**置いてある）と、
/// **べた書きの期待値**で見るので、緩めれば必ず赤くなる。
pub(crate) fn line_with_field<'a>(output: &'a str, field: &str) -> &'a str {
    output
        .lines()
        .find(|line| has_field(line, field))
        .unwrap_or_else(|| panic!("欄 {field:?} を持つ行があること: {output:?}"))
}

/// `キー=[…]` の**閉じ括弧までを1つの値として**読む（作業単位 B-12b）。
///
/// # なぜ [`has_field`] では務まらないのか
///
/// あちらは `split_whitespace` で割るので、**値に空白が入る欄には使えない。**
/// `Debug`（`?`）で載せた列がまさにその形になる:
///
/// | 載り方 | 空白 |
/// |---|---|
/// | 0 件（`[]`） | 入らない。[`has_field`] で読める |
/// | 1 件（`["内なる 情熱"]`） | **軸名の中間に入りうる**（`StatAxis` は中間の空白を保つ） |
/// | 2 件以上（`["A", "B"]`） | **区切りに必ず入る** |
///
/// **値に空白が入らない綴りだけでフィクスチャを組むと、
/// [`has_field`] でも緑になる**——それはフィクスチャに寄りかかった締め方で、
/// 2 件目が載った瞬間に偽陽性で落ちる。
///
/// # 0 件（`[]`）に限れば、[`has_field`] と**受理集合が同値**（作業単位 B-21b）
///
/// 値に空白が入らないので、下の規則 1. と 3.（キーとトークンの境目）が
/// **[`has_field`] のトークン完全一致とちょうど同じ**に潰れる。
/// **検出力は等価**——欄名を伸ばす変異でも値を伸ばす変異でも、**どちらの道具でも赤になる**
/// （B-21b で両方向を実測）。
///
/// **だから 0 件の欄をどちらで読むかは、優劣ではなく「その場所の一貫性」で決めてよい。**
/// **⚠ 現に2箇所で別の道具を使っている。どちらも正しい:**
///
/// | 読む側 | 使うもの | 何に揃えているか |
/// |---|---|---|
/// | `src/server/turn.rs` | [`has_field`] | 同じファイルの他の欄の読み方 |
/// | `tests/server_chat_parse_log.rs` | この関数 | 同じテストの**1件ある側**（B-12b が締めた2本） |
///
/// **⚠ ここが両者の権威。呼び出し側にこの理由を書き写さないこと**
/// ——B-21b のレビューが「**逆向きの理由が2箇所にあり、突き合わせる見張り番が無い**」として
/// 指摘した形。**片方を直しても、もう片方が黙って古びる。**
///
/// # 判定の規則（**3つとも満たしたときだけ値を返す**）
///
/// 1. **キーはトークンの先頭**にあること（直前は行頭か空白）。
///    ——`x` を足しただけの**別の欄**（キーの側が伸びた形）に当たらない。
/// 2. `[` から**最初の `]` まで**を値とする。**途中の空白は値の一部。**
/// 3. **その `]` でトークンが終わる**こと（直後は行末か空白）。
///    ——**1文字でも伸びた値**（`["A"]!`）を「同じ値」と読まない。
///
/// **⚠ 否定（「その欄が無いこと」）には使わないこと。**
/// 読めなければ `None` を返すので、**綴りが変わっただけ**でも主張が成立してしまう。
///
/// **否定に何を使うかは [`has_field`] の doc の表が権威**（作業単位 B-21 / B-21d）。
/// **ここに書き写さない**——写すと、片方を直したときにもう片方が黙って古びる。
/// **`キー=[…]` の欄について「その欄を出さないこと」を言うなら [`has_key`]**
/// （`キー=` で始まるトークンを見るので、`[` の中身に左右されない）。
///
/// # 呼び出し側は `Some(期待値)` と比べること
///
/// **`if let` で畳まない。** 畳むと**欄が丸ごと消えた変異が「読めなかったので
/// 何も主張しない」で緑**になる（`line_containing` が `Option` を返さないのと同じ理由）。
/// `assert_eq!(…, Some(期待値))` なら、`None` は必ず赤になる。
///
/// # 読めない形（**うるさく落ちる方へ倒してある。実測済み**）
///
/// 値の中に `]` がある（`["a]b"]`）と、2. が手前で切って 3. が満たされないので `None`。
/// **`StatAxis` は `]` を許す**ので、これは机上の話ではない
/// ——**軸名を `"内なる ]情熱"` にして実際に測った**（2026-08-27 / B-12b）:
///
/// | 問い | 実測 |
/// |---|---|
/// | `StatAxis::parse` は `]` を通すか | **通す**（正規化も変えない） |
/// | 漏れたときテストは落ちるか | **落ちる**（`left: None` / `right: Some("[\"内なる ]情熱\", …")`） |
/// | 本番の観測は止まるか | **止まらない。** 行は正しく出ており、拒んだのは**この関数だけ** |
///
/// **失敗の文面に行がまるごと出る**ので、読めば1秒で原因が分かる。
/// **偽陽性はこの向きで受け入れる**——逆向き（伸びた値を同じと読む偽陰性）は黙って通り、
/// それが B-12b の出発点だった。
///
/// **⚠ ログの書式そのものは変えていない。** `Debug` は `]` をエスケープしないので、
/// **同じ曖昧さは集計側にもある**（本番の欄の形の話で、この関数の話ではない）。
///
/// # 一本化しただけでは守られない
///
/// [`line_containing`] / [`has_field`] と同じ穴がある——**呼び出し側は全員この関数で
/// 欄を読む**ので、ここが緩めば呼び出し側の判定も一緒に緩む。
/// **この関数の外にある値で押さえる見張り番**が [`crate::testlog`] にあり、
/// 入力も期待値も**関数を通さないべた書き**にしてある。
pub(crate) fn bracketed_field<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    let opening = format!("{key}=[");

    line.match_indices(&opening).find_map(|(at, _)| {
        // 1. **キーはトークンの先頭**（直前は行頭か空白）。
        let key_starts_a_token = line[..at]
            .chars()
            .next_back()
            .is_none_or(|before| before.is_whitespace());
        // 2. `[` から**最初の `]` まで**を値とする（途中の空白は値の一部）。
        let value = line.get(at + opening.len() - 1..)?;
        let close = value.find(']')?;
        // 3. **その `]` でトークンが終わる**（直後は行末か空白）。
        let value_ends_the_token = value[close + 1..]
            .chars()
            .next()
            .is_none_or(|after| after.is_whitespace());

        (key_starts_a_token && value_ends_the_token).then(|| &value[..=close])
    })
}

/// `キー="…"` の**閉じ引用符までを1つの値として**読む（作業単位 B-32）。
///
/// [`bracketed_field`] の**引用符版**。`Debug`（`?`）で載せた**文字列**がこの形になる。
///
/// # なぜ [`bracketed_field`] では務まらないのか
///
/// あちらが探すのは `[` で始まる値（`Debug` の**列**）で、
/// 文字列の `"` は読まない。**列の中の引用符**（`["a"]`）とは別の話である。
///
/// # なぜ [`has_field`] では務まらないのか
///
/// あちらは `split_whitespace` で割るので、**値に空白が入る欄には使えない。**
/// `Debug` の文字列は**中身をそのまま写す**ので、空白は普通に入る。
///
/// # なぜ素の `find("キー=\"")` では務まらないのか（**実測された穴**）
///
/// **キーがトークンの先頭にあることを見ないので、名前が伸びた別の欄の中から読む。**
/// `server::drift` の生出力の欄がこの形で、
/// **欄名に接頭辞を足す変異が、値を読む見張り番を全部緑のまま通した**
/// （2026-09-02 / B-21e の変異検査。是正は B-32）。
/// **是正後は同じ変異が 5 赤**（値を読む 4 本＋欄名の走査 1 本）。
///
/// # 判定の規則（**3つとも満たしたときだけ値を返す**）
///
/// 1. **キーはトークンの先頭**にあること（直前は行頭か空白）。
///    ——`x` や `x_` を足しただけの**別の欄**に当たらない。
/// 2. 開き引用符の次から、**エスケープされていない `"`** までを値とする。
///    **`Debug` は引用符を `\"` と書く**ので、そこでは切らない。
///    **途中の空白も改行のエスケープも値の一部。**
/// 3. **その閉じ引用符でトークンが終わる**こと（直後は行末か空白）。
///    ——**1文字でも伸びた値**を「同じ値」と読まない。
///
/// # 返すのは**`Debug` が書いたままの中身**（復号しない）
///
/// `\n` は**2文字のまま**返る。**復号すると、生の改行を含む値と区別が付かなくなる**
/// ——「1イベントが1行に収まっていること」を見る呼び出し側が、その差を見ている。
///
/// **⚠ 否定（「その欄が無いこと」）には使わないこと**（[`bracketed_field`] と同じ理由）。
/// **否定に何を使うかは [`has_field`] の doc の表が権威。ここに書き写さない。**
///
/// # 呼び出し側は `Some(期待値)` と比べるか、`None` で落とすこと
///
/// **`if let` で畳まない。** 畳むと**欄が丸ごと消えた変異が「読めなかったので
/// 何も主張しない」で緑**になる（[`bracketed_field`] と同じ）。
///
/// # 一本化しただけでは守られない
///
/// [`bracketed_field`] と同じ穴がある——**呼び出し側は全員この関数で欄を読む**ので、
/// ここが緩めば呼び出し側の判定も一緒に緩む。
/// **この関数の外にある値で押さえる見張り番**が [`crate::testlog`] にあり、
/// 入力も期待値も**関数を通さないべた書き**にしてある。
pub(crate) fn quoted_field<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    /// 逆斜線1文字。**`Debug` のエスケープの導入記号。**
    const BACKSLASH: char = '\u{5C}';

    let opening = format!("{key}=\"");

    line.match_indices(&opening).find_map(|(at, _)| {
        // 1. **キーはトークンの先頭**（直前は行頭か空白）。
        let key_starts_a_token = line[..at]
            .chars()
            .next_back()
            .is_none_or(|before| before.is_whitespace());
        // 2. 開き引用符の次から、**エスケープされていない `"`** まで。
        let body = line.get(at + opening.len()..)?;
        let mut escaped = false;
        let close = body.char_indices().find_map(|(offset, character)| {
            if escaped {
                escaped = false;
                return None;
            }
            match character {
                BACKSLASH => {
                    escaped = true;
                    None
                }
                '"' => Some(offset),
                _ => None,
            }
        })?;
        // 3. **その閉じ引用符でトークンが終わる**（直後は行末か空白）。
        let value_ends_the_token = body[close + 1..]
            .chars()
            .next()
            .is_none_or(|after| after.is_whitespace());

        (key_starts_a_token && value_ends_the_token).then(|| &body[..close])
    })
}

