/// 出力を溜めるライタ。**`src/` と `tests/` が同じ1本を読む**（作業単位 B-3）。
///
/// # 何が畳めて、何が畳めなかったか
///
/// B-3 より前は、この型と `Write` / `MakeWriter` の実装が
/// **`tests/` の3ファイルと `src/testlog.rs` に、計4つ複製されていた。**
/// 4つは少しずつ違っていて（`from_utf8` と `from_utf8_lossy` ／ 区間を切れるかどうか）、
/// **どれが正しいのかを言う権威がどこにも無かった。**
///
/// | もの | 畳めたか |
/// |---|---|
/// | 型・`std::io::Write`・`MakeWriter` | **畳んだ**（ここ） |
/// | グローバルの subscriber を差す手順 | **畳んだ**（[`install_global_log`]） |
/// | **テストバイナリを分けていること** | **畳めない**（[`install_global_log`] の doc） |
///
/// # 中身の取り出しは**うるさく落ちる側**（`from_utf8_lossy` ではない）
///
/// **B-3 より前は `src/testlog.rs` だけが `String::from_utf8(..).expect(..)` で、
/// `tests/` の3本は全部 lossy** だった。**厳しい側へ揃えた**
/// ——多数決ではなく、**どちらの壊れ方が良いか**で決める。
///
/// **`tracing` の fmt 層は正当な UTF-8 しか書かない。**
/// したがって不正な UTF-8 が出てくるとすれば、それは
/// **[`Self::contents_since`] が文字の途中で切ったとき**——
/// **つまり `mark` の扱いが壊れたとき**である。
///
/// | | 起きること |
/// |---|---|
/// | lossy | **U+FFFD になって黙って進む。** 突き合わせがたまたま通れば**壊れた区間のまま緑** |
/// | 厳しい側 | **その場で落ちる。** `mark` の仕掛けが壊れていると即座に分かる |
///
/// **[`bracketed_field`] と同じ立場**（値に `]` が入ったら半分を答えず `None` にする）。
/// **偽陽性はうるさく落ちるだけ。偽陰性は黙って通る。**
///
/// **⚠ 「落ちる側へ倒した」は測ってから書いている。** 見張り番は [`crate::testlog`] の
/// `a_mark_in_the_middle_of_a_character_fails_loudly`
/// （**文字の途中の `mark` を実際に作って落ちることを見る**）と、
/// その対照 `a_mark_on_a_character_boundary_reads_the_multibyte_text_back`。
///
/// # 一本化しただけでは守られない
///
/// [`line_containing`] と同じ穴がある —— **呼び出し側は全員この器の中身を観測対象にする**ので、
/// [`Self::contents_since`] が区間を無視すれば、区間を見ている主張は一緒に緩む。
/// **この型の外にある値で押さえる見張り番**が [`crate::testlog`] にあり、
/// **入力は `tracing` を通さないべた書きのバイト列**にしてある。
#[derive(Clone, Default)]
pub(crate) struct SharedBuffer(std::sync::Arc<std::sync::Mutex<Vec<u8>>>);

impl SharedBuffer {
    /// 今までに溜まった長さ。**「自分の区間」の左端。**
    ///
    /// グローバルの subscriber はバイナリで1つしか差せない（[`install_global_log`]）ので、
    /// 同じバッファに他のテストの行が混ざる。**その弊害を約束事ではなく仕掛けで潰す**ための入口
    /// （使う側は `tests/server_chat_parse_log.rs` の `LogSection`）。
    pub(crate) fn mark(&self) -> usize {
        self.0.lock().expect("ロックを取れること").len()
    }

    /// `mark` より**後ろに出た分だけ**を返す。
    ///
    /// バッファは伸びる一方なので `mark` が末尾を超えることはないが、
    /// 越えていたら**空**として扱う（テストが「何も出ていない」で緑にならないよう、
    /// 肯定側の主張は必ず「行があること」の形で書くこと）。
    ///
    /// **⚠ 文字の途中で切ったら、黙って U+FFFD にせず落ちる**（型の doc）。
    /// `tracing` は正当な UTF-8 しか書かないので、**ここが落ちるのは `mark` の側が壊れたとき。**
    pub(crate) fn contents_since(&self, mark: usize) -> String {
        let bytes = self.0.lock().expect("ロックを取れること");
        let tail = bytes.get(mark..).unwrap_or_default();

        std::str::from_utf8(tail)
            .unwrap_or_else(|err| {
                panic!(
                    "捕捉した内容が UTF-8 として読めません（`mark` の扱いを疑うこと）: \
                     mark = {mark} / 全体 = {} バイト / {err}",
                    bytes.len()
                )
            })
            .to_owned()
    }

    /// バッファ**全体**（他のテストが出した行も含む）。
    ///
    /// 否定側（「載っていないこと」）はこちらで見る。区間に狭めると弱くなるだけだから。
    pub(crate) fn contents(&self) -> String {
        self.contents_since(0)
    }
}

impl std::io::Write for SharedBuffer {
    fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
        self.0
            .lock()
            .expect("ロックを取れること")
            .extend_from_slice(buf);
        Ok(buf.len())
    }

    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

impl<'a> tracing_subscriber::fmt::MakeWriter<'a> for SharedBuffer {
    type Writer = Self;

    /// **同じバッファを指す handle** を返す（`Arc` の複製なので中身は共有される）。
    ///
    /// ここが `Self::default()`（＝新しい空のバッファ）に化けると、
    /// **どのテストも何も観測しなくなる。** 見張り番は [`crate::testlog`] の
    /// `the_writer_handed_to_the_subscriber_shares_the_buffer`。
    fn make_writer(&'a self) -> Self::Writer {
        self.clone()
    }
}

/// **プロセス全体の subscriber を1回だけ差し、共有のバッファを返す**（作業単位 B-3）。
///
/// # 「1プロセス1回」は「共有できない」を意味しない
///
/// `tracing::subscriber::set_global_default` は**プロセスにつき1回**しか成功しない。
/// それでもこの関数は共有できる —— **`#[path]` で取り込まれたこのファイルは、
/// 取り込んだクレートごとに別々にコンパイルされる**ので、
/// 下の `LOG` は**テストバイナリごとに別の静的変数**になる。
/// cargo は `tests/*.rs` を1本ずつ別バイナリ（＝別プロセス）にするから、
/// 「1プロセス1回」と「1バイナリ1回」がちょうど一致する。
///
/// # 畳めないのは、この関数ではなく「バイナリを分けていること」
///
/// **同じプロセスの中に、独立した捕捉窓を2つ作ることはできない。**
/// だからグローバルの subscriber が要るテストは**ファイルごと分けて**置くしかない
/// （`tests/server_chat.rs` / `tests/server_chat_stream.rs` /
/// `tests/server_chat_parse_log.rs` / `tests/server_context_refresh.rs` の4本）。
/// **この4分割だけは、どう書いても消せない。**
///
/// # 「1回だけ」は約束ではなく `OnceLock` が保証する
///
/// B-3 より前は、4本のうち**2本**（`server_chat` / `server_chat_stream`）が
/// **テストの本文に素の `set_global_default(..).expect(..)` を直接書いていた。**
/// 根拠は「このバイナリで呼ぶのはここだけ」というコメントだけで、
/// **2本目のテストが同じことをすれば panic するまで気付けない。**
/// 残り2本（`server_chat_parse_log` / `server_context_refresh`）は `OnceLock` だった。
/// **`OnceLock` の側へ揃えた。** 同じ綴りでの2度目以降は、同じバッファを返すだけになる。
///
/// # **違う綴りでの2度目は落とす**（B-3 のレビュー指摘 / 是正1）
///
/// **グローバルの subscriber は差し替えられない。**
/// だから2度目に違うフィルタを渡されたら、**できるのは「黙って別の綴りで走る」か
/// 「落ちる」かの二択**しかない。
///
/// | | 2度目に違う綴りを渡したとき |
/// |---|---|
/// | B-3 前（素の `set_global_default`） | **必ず panic した** |
/// | 素の `OnceLock`（B-3 の最初の版） | **黙って最初の綴りのまま走った** ← **後退** |
/// | いま | **`assert_eq!` で落ちる**（綴りも一緒に控える） |
///
/// 黙る版の具体的な壊れ方——**`install_global_log(VERBOSE_FILTER)` を使う
/// ログ観測テストを足すと、既定のフィルタのまま走る。**
/// **否定側の主張なら「何も出なかった」で緑を通る。**
/// [`SharedBuffer`] の復号を厳しい側へ倒したのと**同じ向き**にしてある
/// ——**偽陽性はうるさく落ちるだけ。偽陰性は黙って通る。**
///
/// **見張り番は `tests/log_filter_wiring.rs` の1本**（同じ綴りでの2度目＝落ちない側と、
/// 違う綴りでの2度目＝落ちる側を、**同じテストの中で順番を固定して**対にしてある。
/// `should_panic` は「落ちた」しか言わないので使っていない）。
#[allow(
    dead_code,
    reason = "グローバルの subscriber を差すのは統合テストだけ（`src/**` は `with_default`）"
)]
pub(crate) fn install_global_log(filter: &str) -> &'static SharedBuffer {
    // **差した綴りも一緒に控える。** バッファだけを控えると、2度目に違う綴りを
    // 渡されても比べる相手が無く、黙って最初の綴りのまま走る（上の doc の表）。
    static LOG: std::sync::OnceLock<(String, SharedBuffer)> = std::sync::OnceLock::new();

    let (installed, buffer) = LOG.get_or_init(|| {
        let buffer = SharedBuffer::default();
        let subscriber = tracing_subscriber::fmt()
            .with_env_filter(tracing_subscriber::EnvFilter::new(filter))
            .with_ansi(false)
            .with_writer(buffer.clone())
            .finish();
        tracing::subscriber::set_global_default(subscriber)
            .expect("グローバルの subscriber を差すのはここだけであること");
        (filter.to_owned(), buffer)
    });

    assert_eq!(
        installed.as_str(),
        filter,
        "グローバルの subscriber は差し替えられません\
         （このまま進むと、先に差した綴りのまま黙って走ります）"
    );

    buffer
}
