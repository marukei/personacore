/**
 * **画面に出す時刻の綴り**（作業単位 F-7 → **F-7b で地域化した** / `src/lib/timestamp.ts`）。
 *
 * # なぜ引数で時間帯を受け取るのか（**この測定の存在理由**）
 *
 * F-7 は**地域化しない**と決めていた。理由は2つ書かれていた ——
 *
 * 1. 画面の値がログ・`sqlite3` と食い違い、**どちらの時計かが画面のどこにも出ない**
 * 2. **その綴りを見張る検査が、走らせた機械の時間帯でしか成立しなくなる**
 *
 * **利用者の判断で 1 は覆った**（「sqlite が UTC で保持していれば、
 * ブラウザの時間帯で出せばよい」）。**そして印を出すので、食い違いは読み解ける** ——
 * `(UTC+09:00)` から 9 時間引けばログの値に戻る。
 *
 * **2 は、時間帯を引数で受け取ることで消える。**
 * **書式を見る節は `process.env.TZ` を1バイトも触らない** ——
 * 時間帯を全部**呼び出し側が名指し**するので、
 * **どの機械で走らせても同じ結果になる。**
 *
 * **⚠ 例外は、いちばん下の `browserZone` の節だけ**（F-7b のレビューの提案D）。
 * **あれの存在理由が「機械に訊く」ことなので、訊く先を動かさずには測れない。**
 * **そこだけが `TZ` を立てて、必ず機械の値へ戻す。**
 * **「このファイルは `TZ` を触らない」と読めると、あとから
 * 書式の節に `TZ` 依存を持ち込む経路ができるので、ここで限定しておく。**
 *
 * # 期待値は直書き
 *
 * `timeLabel` から作ると、**綴りを変える変異が期待値も一緒に動かして緑**になる
 * （CLAUDE.md「写しを1つにしても、その1つは自動的には守られない」）。
 *
 * **⚠ 下の期待値は、実装から出したものではない。**
 * 東京は年間を通して UTC+9（夏時間なし）、ニューヨークは 8 月が EDT (UTC-4)・
 * 1 月が EST (UTC-5)、**切り替えは 3 月の第2日曜と 11 月の第1日曜の現地 02:00**、
 * コルカタは UTC+5:30、チャタム諸島の標準時は UTC+12:45 ——
 * という**外の事実から手で足し引きして書いた。**
 */

import { describe, expect, it } from "vitest";

import { browserZone, timeLabel } from "../src/lib/timestamp";
import { enterZone, machineZone } from "./support/zone";

/** サーバが返す綴り（`DateTime<Utc>` / RFC 3339 / `Z` 終わり）。 */
const INSTANT = "2026-08-28T14:13:44.983Z";

describe("画面に出す時刻の綴り（作業単位 F-7b）", () => {
  /**
   * **読み手の時間帯で出す。**
   *
   * 14:13 UTC は東京の 23:13。**日付は変わらない時刻**を、まずここで見る
   * （日をまたぐ側は下の測定が持つ）。
   */
  it("渡された時間帯の壁時計で出す", () => {
    expect(timeLabel(INSTANT, "Asia/Tokyo")).toBe(
      "2026-08-28 23:13:44 (UTC+09:00)",
    );
  });

  /**
   * **⚠ 同じ瞬間が、時間帯によって別の日になる。**
   *
   * **同値のフィクスチャでは帰属を見張れない**（CLAUDE.md の最頻の穴）。
   * **`20:00Z` は東京では翌日の 05:00、ニューヨークでは同日の 16:00** ——
   * **日付そのものが違う**ので、**時間帯を無視して UTC のまま出す実装**も、
   * **どちらか一方の時間帯を決め打つ実装**も、この1本で赤になる。
   */
  it("日をまたぐ瞬間が、時間帯ごとに別の日付で出る", () => {
    const crossing = "2026-08-28T20:00:00Z";

    expect(timeLabel(crossing, "Asia/Tokyo")).toBe(
      "2026-08-29 05:00:00 (UTC+09:00)",
    );
    expect(timeLabel(crossing, "America/New_York")).toBe(
      "2026-08-28 16:00:00 (UTC-04:00)",
    );
  });

  /** **逆向きにも日をまたぐ**（UTC の未明は、西側では前日）。 */
  it("UTC の未明が、西の時間帯では前日になる", () => {
    expect(timeLabel("2026-08-28T02:30:00Z", "America/New_York")).toBe(
      "2026-08-27 22:30:00 (UTC-04:00)",
    );
  });

  /**
   * **時差 0 のときだけ、印は `(UTC)`。**
   *
   * F-7 の綴りがそのまま残る枝。**`(UTC+00:00)` にしない** ——
   * 読み手にとって `+00:00` は情報を1つも足さない。
   */
  it("時差が無い時間帯では、印は (UTC) のまま", () => {
    expect(timeLabel(INSTANT, "UTC")).toBe("2026-08-28 14:13:44 (UTC)");
  });

  /**
   * **時差は「時」だけではない。**
   *
   * 30 分・45 分の時間帯を落とすと、**印だけが嘘になって値は正しい**という
   * いちばん気付きにくい壊れ方をする。
   */
  it("30 分・45 分の時差も、印と壁時計の両方に出る", () => {
    // コルカタは UTC+5:30。14:13:44 + 5:30 = 19:43:44。
    expect(timeLabel("2026-08-28T14:13:44Z", "Asia/Kolkata")).toBe(
      "2026-08-28 19:43:44 (UTC+05:30)",
    );
    // チャタム諸島の標準時は UTC+12:45（7 月は南半球の冬＝標準時）。
    expect(timeLabel("2026-07-15T03:00:00Z", "Pacific/Chatham")).toBe(
      "2026-07-15 15:45:00 (UTC+12:45)",
    );
  });

  /**
   * **⚠ 時差は「その瞬間」のもの。「いま」のものではない。**
   *
   * 同じ時間帯・別の季節。**現在時刻から時差を引く実装**は、
   * **走らせた日によって片方が外れる**（そして走らせた日によっては緑になる）。
   * **1 月と 8 月を1本に置いてある**ので、その実装はどの日に走らせても赤になる。
   */
  it("夏時間が、その瞬間の時差で出る（いまの時差ではない）", () => {
    // 1 月のニューヨークは EST = UTC-5。
    expect(timeLabel("2026-01-15T12:00:00Z", "America/New_York")).toBe(
      "2026-01-15 07:00:00 (UTC-05:00)",
    );
    // 7 月のニューヨークは EDT = UTC-4。**同じ時間帯・同じ実装・別の答え。**
    expect(timeLabel("2026-07-15T12:00:00Z", "America/New_York")).toBe(
      "2026-07-15 08:00:00 (UTC-04:00)",
    );
  });

  /**
   * **⚠ 夏時間の「境目」の日**（F-7b のレビューが見つけた穴）。
   *
   * 上の測定は**1月と7月で、どちらも境目から遠い。**
   * **時差をその日の `00:00Z` で決める実装が 658 全緑を通った** ——
   * `2026-03-08T12:00:00Z` に `(UTC-05:00)` と書く（正しくは `-04:00`）。
   * **壁時計は正しく、印だけが嘘になる。**
   *
   * **⚠ これは 30/45 分の測定が「いちばん気付きにくい壊れ方」と
   * 自分で名指しした形そのもの**で、夏時間の側だけ状態が作られていなかった。
   *
   * **⚠ そしてこの設計の正当化そのものが揺らぐ** ——
   * 「時差なら引き算でログ・`sqlite3` の UTC へ戻せる」が、
   * **境目の日だけ1時間ずれる。**
   *
   * # なぜ1本で足りるのか
   *
   * **同じ日・同じ時間帯に、時差が2つ出る。**
   * 米国の切り替えは現地 `02:00`（`07:00Z`）なので、
   * その前後1時間を挟むと **`01:30` は EST、`03:30` は EDT** になる。
   * **`02:xx` はこの日に存在しない**（1時間飛ぶ）ので、
   * 壁時計の側も一緒に押さえられる。
   */
  it("夏時間の境目の日に、同じ時間帯で時差が2つ出る", () => {
    // 切り替えの直前（現地 01:30）——まだ標準時。
    expect(timeLabel("2026-03-08T06:30:00Z", "America/New_York")).toBe(
      "2026-03-08 01:30:00 (UTC-05:00)",
    );
    // 切り替えの直後（現地 03:30）——**02 時台は飛んでいる。**
    expect(timeLabel("2026-03-08T07:30:00Z", "America/New_York")).toBe(
      "2026-03-08 03:30:00 (UTC-04:00)",
    );
  });

  /**
   * **戻る側の境目**（秋）。**同じ壁時計が2回来る。**
   *
   * 春の測定だけだと、**「その日の正午で決める」実装**が通る
   * （3/8 の正午はすでに EDT なので当たってしまう）。
   * ここは **`01:30` が2回来て、時差だけが違う** ——
   * **壁時計は完全に同値なので、印を見ていなければ区別できない。**
   */
  it("秋の境目では、同じ壁時計が別の時差で2回出る", () => {
    const seen = [
      timeLabel("2026-11-01T05:30:00Z", "America/New_York"),
      timeLabel("2026-11-01T06:30:00Z", "America/New_York"),
    ];

    expect(seen).toEqual([
      "2026-11-01 01:30:00 (UTC-04:00)",
      "2026-11-01 01:30:00 (UTC-05:00)",
    ]);
    // **壁時計は同じ。印だけが違う。**
    expect(seen[0]).not.toBe(seen[1]);
  });

  /**
   * **真夜中が `00` で出る**（`24` ではない / F-7b のレビューの提案C）。
   *
   * 実装は `hour12: false` ではなく **`hourCycle: "h23"`** を名指ししている。
   * **前者は真夜中を `24` と綴る実装がある**ので等価ではない ——
   * **その差が出るのは真夜中だけ**で、フィクスチャに1件も無かった。
   */
  it("真夜中が 00 で出る（24 ではない）", () => {
    expect(timeLabel("2026-08-28T00:00:00Z", "UTC")).toBe(
      "2026-08-28 00:00:00 (UTC)",
    );
    // **時間帯をまたいで真夜中になる側**（東京の 00:00 は前日の 15:00Z）。
    expect(timeLabel("2026-08-27T15:00:00Z", "Asia/Tokyo")).toBe(
      "2026-08-28 00:00:00 (UTC+09:00)",
    );
  });

  /**
   * **欄の並びを取り違えない。**
   *
   * 年・月・日・時・分・秒を**全部違う数**にしてある ——
   * 2つでも同値にすると、その入れ替えは観測できない（CLAUDE.md の最頻の穴）。
   * **時差 0 の時間帯で見る**ので、数字は入力のまま出る。
   */
  it("年・月・日・時・分・秒が、その順のまま出る", () => {
    expect(timeLabel("2023-04-05T06:07:08.123Z", "UTC")).toBe(
      "2023-04-05 06:07:08 (UTC)",
    );
  });

  /**
   * **⚠ 引数の時間帯を、実際に使っている。**
   *
   * `B-7` の形（CLAUDE.md）—— **実行時に決まる値を入れたら、
   * その値が既定と違う状態で回る腕を1本置くこと。**
   * ここでは**同じ入力を4つの時間帯に通して、4つとも別の答え**になることを見る。
   * **引数を捨てて中で決めている実装**は、どの時間帯を選んでいても赤になる
   * （4つのうち3つが外れる）。
   */
  it("時間帯ごとに別の答えを返す（引数を捨てていない）", () => {
    const seen = [
      "UTC",
      "Asia/Tokyo",
      "America/New_York",
      "Asia/Kolkata",
    ].map((zone) => timeLabel(INSTANT, zone));

    expect(seen).toEqual([
      "2026-08-28 14:13:44 (UTC)",
      "2026-08-28 23:13:44 (UTC+09:00)",
      "2026-08-28 10:13:44 (UTC-04:00)",
      "2026-08-28 19:43:44 (UTC+05:30)",
    ]);
    // **4つとも別の綴り**（同値化していないことを、値そのもので押さえる）。
    expect(new Set(seen).size).toBe(4);
  });

  /**
   * **機械の綴りを画面に出さない**（作業単位 F-8 と同じ目）。
   *
   * `Asia/Tokyo` は**時間帯データベースの識別子**であって、読み手の言葉ではない。
   * 印は**時差**で名乗る —— どの国の略称も知らずに読めて、
   * **ログの UTC へ引き算で戻せる**（F-7 の当初の理由が、これで守られる）。
   */
  it("時間帯データベースの識別子を、画面に出さない", () => {
    const label = timeLabel(INSTANT, "Asia/Tokyo");

    expect(label).not.toContain("Asia");
    expect(label).not.toContain("Tokyo");
    expect(label).not.toContain("/");
    // **機械の綴りは畳んである**（F-7 の性質）。
    expect(label).not.toContain("T23");
    expect(label).not.toContain("Z");
    expect(label).not.toContain(".983");
  });

  /**
   * **知らない綴りは、そのまま返す**（F-7 の性質 / 回帰）。
   *
   * **推測で直さない** —— 直すと、読み手は「サーバがそう言った」と読む。
   * **時差つきの綴りもここに入る**（サーバは UTC しか返さないが、
   * 来た日に**黙って時間帯を名乗る**のがいちばん悪い）。
   *
   * **⚠ 時差のある時間帯を渡して見る。** UTC で見ると
   * 「そのまま返した」と「畳んだ結果がたまたま同じ」の区別が甘くなる。
   */
  it("読めない綴りは、そのまま返す", () => {
    for (const raw of [
      "",
      "きのう",
      "2026-08-28",
      "2026-08-28T14:13:44",
      "2026-08-28T14:13:44+09:00",
      "2026-08-28 14:13:44 (UTC)",
      // **正規表現には当たるが、日付として無効な綴り**
      // （F-7b のレビューの提案A / 一覧に1件も無かった）。
      // **桁は合っているので `\d{4}-\d{2}-\d{2}T…` を通り抜ける。**
      // いまの振る舞い（`new Date` が `Invalid Date` になり、
      // `formatToParts` が投げて `null` に落ちる）は正しいので、
      // **ここは見張り番を置くだけ。**
      "2026-13-45T25:61:61Z",
      "2026-00-00T00:00:00Z",
    ]) {
      expect(timeLabel(raw, "Asia/Tokyo"), `そのまま返すこと: ${raw}`).toBe(raw);
    }
  });

  /**
   * **4桁未満の年でも、存在しない時差を名乗らない**（F-7b のレビューの提案A）。
   *
   * # 何が起きていたか
   *
   * **`Date.UTC` は 0〜99 の年を 1900 年代へ読み替える。**
   * `0026-08-28T14:13:44Z` の壁時計は正しく出るのに、
   * 引き算の相手だけが 1926 年になって
   * **`(UTC+16655035:04)` という存在しない時差**が出ていた。
   * `0000-…` に至っては**年まで `0002` に変わっていた。**
   *
   * # なぜ直したのか
   *
   * **doc が「読めなければ手を出さない／黙って別の時間帯へ動かすのがいちばん悪い」
   * と書いているのに、ここは黙って存在しない時間帯を名乗っていた。**
   * **到達経路は現実には無い**（サーバは `DateTime<Utc>` しか返さない）が、
   * **doc の約束を実装に戻すだけの話**なので直してある。
   *
   * **期待値は手で出した** —— ニューヨークは 1883 年より前は地方平時 (LMT) で、
   * **UTC-4:56**。だから時差は `(UTC-04:56)` になる（`-05:00` ではない）。
   */
  it("4桁未満の年でも、存在しない時差を名乗らない", () => {
    const label = timeLabel("0026-08-28T14:13:44Z", "America/New_York");

    // **年が動いていない**（`Date.UTC` の読み替えが起きていない）。
    expect(label).toContain("0026-08-28");
    // **時差が、時間帯として有り得る大きさに収まっている。**
    expect(label).toMatch(/\(UTC[+-]\d{2}:\d{2}\)$/u);
    expect(label).not.toContain("16655035");
    expect(label).toBe("0026-08-28 09:17:42 (UTC-04:56)");
  });

  /**
   * **年 0 は、そのまま返す**（下端）。
   *
   * ここは畳めない —— **`en-US` は年 0 を「紀元前 1 年」として `1` と綴る**
   * （`era` を要求していないので紀元の区別が落ちる）ため、
   * **壁時計そのものが `0001-01-01` になってしまう。**
   *
   * **年ごとに特例を書くのではなく、`MAX_ZONE_OFFSET_MINUTES` の門で塞いである** ——
   * **有り得ない時差が出たら、印を名乗らずに入力を返す。**
   * **`0002` や `(UTC+8784:00)` を黙って出すより、生の綴りのほうが嘘が少ない。**
   */
  it("年 0 は、畳まずにそのまま返す", () => {
    expect(timeLabel("0000-01-01T00:00:00Z", "UTC")).toBe(
      "0000-01-01T00:00:00Z",
    );
  });

  /**
   * **対照: 門が広すぎないこと。**
   *
   * 上の門は**有り得ない時差だけ**を弾く。
   * **実在する下端・上端の時間帯は、いままでどおり畳む。**
   * ここが無いと、**門を「常に入力を返す」に潰す変異**が
   * 上の1本だけを緑にして通り抜ける。
   */
  it("対照: 実在する端の時間帯は、門に掛からない", () => {
    // 東端（UTC+14:00）。
    expect(timeLabel("2026-08-28T00:00:00Z", "Pacific/Kiritimati")).toBe(
      "2026-08-28 14:00:00 (UTC+14:00)",
    );
    // 西端（UTC-11:00）。
    expect(timeLabel("2026-08-28T00:00:00Z", "Pacific/Niue")).toBe(
      "2026-08-27 13:00:00 (UTC-11:00)",
    );
  });

  /**
   * **読めない時間帯も、そのまま返す。**
   *
   * **規則は1つ** ——「読めなかったら手を出さない」。
   * **黙って UTC と名乗らない** —— 生の綴りは自分で `Z` と名乗っているので、
   * そのまま出すほうが嘘が少ない。
   * （`browserZone()` は必ず正当な識別子を返すので、これは防具として置いてある。）
   */
  it("読めない時間帯を渡されても、投げずにそのまま返す", () => {
    for (const zone of ["", "Not/AZone", "Asia/Tokyo "]) {
      expect(timeLabel(INSTANT, zone), `そのまま返すこと: ${zone}`).toBe(
        INSTANT,
      );
    }
  });

  /**
   * **対照: 通る綴りと通らない綴りが、同じ検査の中に居る。**
   *
   * 「全部そのまま返す」実装と「全部畳む」実装の、どちらも赤になる。
   */
  it("対照: 畳む綴りと、畳まない綴りが別々に扱われる", () => {
    const folded = timeLabel(INSTANT, "Asia/Tokyo");
    const untouched = timeLabel("2026-08-28T14:13:44+09:00", "Asia/Tokyo");

    expect(folded).toBe("2026-08-28 23:13:44 (UTC+09:00)");
    expect(untouched).toBe("2026-08-28T14:13:44+09:00");
  });
});

/**
 * **欄の綴りを、読み手の言語設定に任せない**（F-7b のレビューが見つけた穴）。
 *
 * # 何が起きたか
 *
 * **`new Intl.DateTimeFormat("en-US", {` を `undefined` に変える変異が 658 全緑。**
 * **同じ行の doc は「`en-US` を名指しして、読み手の言語設定で欄の綴りが
 * 変わらないようにしてある」と守ったと書いていた。守っていたのは実装だけ。**
 *
 * **⚠ 等価ではない。この機の既定が `ja-JP` で、`ja-JP` の出力が
 * `en-US` とバイト一致するから緑になっただけ**（レビュアーの実測）。
 * **`ar-EG` に固定すると 37 赤**（`٢٠٢٦-٠٨-٢٨` になる / 是正後にこちらで測り直した値）。
 * **ブラウザの locale は利用者のもの**なので、固定を外した瞬間に
 * **アラビア語・ペルシア語の読み手の画面だけが壊れる。**
 *
 * # ⚠ なぜ「呼び出しの形」を見ているのか
 *
 * **`readerInZone` と同じ手が使えない** —— **Windows の Node は
 * `LANG` / `LC_ALL` を見ない**（レビュアーの実測: `LC_ALL=ar-EG` でも
 * `resolvedOptions().locale` は `ja-JP`）。**読み手の locale を測定から動かせない。**
 *
 * # ⚠ これは振る舞いの権威ではない
 *
 * **見ているのは「`Intl.DateTimeFormat` が `"en-US"` で呼ばれたこと」だけ。**
 * **型でも実装でも「表現できなく」はしていない** ——
 * **`"ar-EG"` を直書きする変異は、この1本を素通りする。**
 * 塞いでいるのは**「固定を外す」1種類だけ**である。
 */
describe("欄の綴りを、読み手の言語設定に任せない（作業単位 F-7b）", () => {
  it("壁時計は、固定した locale で組み立てられる", () => {
    const real = Intl.DateTimeFormat;
    const seen: unknown[] = [];

    // **本物へ委譲しつつ、第1引数だけ記録する。**
    class Spy extends real {
      constructor(locales?: unknown, options?: Intl.DateTimeFormatOptions) {
        super(locales as string | undefined, options);
        seen.push(locales);
      }
    }

    try {
      (Intl as { DateTimeFormat: unknown }).DateTimeFormat = Spy;
      // **畳める綴り**を通す（`wallClockIn` まで到達させる）。
      expect(timeLabel(INSTANT, "Asia/Tokyo")).toBe(
        "2026-08-28 23:13:44 (UTC+09:00)",
      );
    } finally {
      (Intl as { DateTimeFormat: unknown }).DateTimeFormat = real;
    }

    // **呼ばれていること**（呼ばれなければ、この検査は何も言っていない）。
    expect(seen.length).toBeGreaterThan(0);
    // **どの呼び出しも locale を固定している**（`undefined` が1つも無い）。
    expect(seen).toEqual(seen.map(() => "en-US"));
  });

  /**
   * **対照: 見張り番そのものが働いていること。**
   *
   * 上の検査は**囮を1つも通していない**と、
   * 「`Intl.DateTimeFormat` を包めていないから空で緑」と区別が付かない
   * （CLAUDE.md「1件も見つからないから緑」と「そもそも探せていないから緑」）。
   * ここで**わざと `undefined` で呼んで、同じ判定が赤になること**を見る。
   */
  it("対照: locale を渡さない呼び出しは、同じ判定で捕まる", () => {
    const seen: unknown[] = [undefined];
    expect(seen).not.toEqual(seen.map(() => "en-US"));
  });
});

/**
 * **ブラウザの時間帯を解決する側**（`browserZone`）。
 *
 * # ⚠ ここだけは `process.env.TZ` を触る
 *
 * **`browserZone` の存在理由が「機械に訊く」ことなので、
 * 訊く先を動かさずには測れない。**
 *
 * **測定ファイルはフォークされた別プロセスで走る**ので（vitest の既定は `forks` /
 * 実測: 2 ファイルで別々の pid）、**ここでの `TZ` は他のファイルへ漏れない。**
 * それでも後始末はする。
 *
 * **⚠ 立てるのは [`enterZone`] 経由**（作業単位 F-7d）——
 * `process.env.TZ` を直に立てても、**「読み手の時間帯」の門は名乗ったと見なさない**ので、
 * 直後の `browserZone()` がその場で落ちる。
 * **`enterZone` は「本当にその時間帯になったか」も確かめる**ので、
 * 下の `expect` が測るものは変わらない
 * （**あれは `browserZone` という別の module の口を見ている**）。
 *
 * [`enterZone`]: ./support/zone
 *
 * # ⚠ 2つの時間帯で見る
 *
 * **1つだと、機械の既定がたまたまその時間帯だったときに
 * 「決め打ち」と区別が付かない**（`B-7` の形）。
 * **2つを別々に名指しすれば、どの1つを決め打っても片方で赤になる。**
 */
describe("ブラウザの時間帯の解決（作業単位 F-7b）", () => {
  /**
   * この測定を読み込んだ時点の、機械の時間帯。**必ずここへ戻す。**
   *
   * **⚠ [`machineZone`] で読むこと**（作業単位 F-7d）——
   * `Intl.DateTimeFormat().resolvedOptions().timeZone` は**門を通る**ので、
   * **まだ名乗っていないこの時点で呼ぶと落ちる。**
   *
   * [`machineZone`]: ./support/zone
   */
  const MACHINE_ZONE = machineZone();

  /**
   * **⚠ 時間帯の別名に注意**（F-7b の着手中に実測）。
   *
   * **`TZ=Asia/Kolkata` を立てて `resolvedOptions()` を読むと
   * `Asia/Calcutta` が返る**（ICU が旧名へ正規化する）。
   * ここで使う2つは**正規化されない綴り**であることを確かめてある。
   * 別名の時間帯をここへ足すと、**実装は正しいのに赤くなる。**
   */
  it("機械が名乗っている時間帯を、そのまま返す", () => {
    try {
      enterZone("America/New_York");
      expect(browserZone()).toBe("America/New_York");

      // **別の時間帯でも付いてくる**（どの1つを決め打っても、ここで落ちる）。
      enterZone("Australia/Adelaide");
      expect(browserZone()).toBe("Australia/Adelaide");
    } finally {
      process.env["TZ"] = MACHINE_ZONE;
    }
  });

  /**
   * **`browserZone()` が返した値は、`timeLabel` がそのまま受け取れる。**
   *
   * 2つを繋いだときに壊れないこと —— **識別子ではない何かを返す実装**
   * （`GMT+9` のような表示用の綴り）は、ここで読めない時間帯になって落ちる。
   */
  it("返り値は、そのまま時間帯として通る", () => {
    try {
      enterZone("America/New_York");
      expect(timeLabel("2026-08-28T20:00:00Z", browserZone())).toBe(
        "2026-08-28 16:00:00 (UTC-04:00)",
      );
    } finally {
      process.env["TZ"] = MACHINE_ZONE;
    }
  });
});
