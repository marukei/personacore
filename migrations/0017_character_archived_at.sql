-- character に archived_at（しまった時刻）を足す（ADR-0049 §決定1 / 作業単位 A-10 / Issue origin#55）。
--
-- NULL は「しまっていない」。値は日時の TEXT（created_at と同じ ISO-8601 UTC の綴り）。
-- しまったキャラクターは GET /v1/models と画面の一覧に出ず、chat は断られる。
-- 中身（会話・記憶・性格値など）は1行も変えないので、NULL に戻せば元どおりになる。
--
-- ============================================================================
-- DEFAULT を置かない（既存の行は全部 NULL から始まる）
-- ============================================================================
--
-- この移行を当てても、いまの DB の振る舞いは1つも変わらない（全員「しまっていない」）。
-- 書き手は src/store/character.rs の UPDATE_CHARACTER だけで、時刻は SQL の strftime で書く
-- （created_at の DEFAULT と同じ綴り。CLAUDE.md の D-5a の注意 —— 読む側が割れない綴りにする）。
--
-- ============================================================================
-- CHECK は型だけを縛る
-- ============================================================================
--
-- 日時として読めるかは SQL では確かめない（読み出し側が確かめ、読めない行は一覧で指し示す /
-- domain::CharacterColumn::ArchivedAt）。typeof を縛るのは、BLOB が入ると読み出しの
-- デコードそのものが割れて、一覧が丸ごと落ちるため。TEXT 宣言の列なので数値は TEXT に直って入る。
--
-- DEFAULT が CHECK を満たさないと ADD COLUMN そのものが失敗する（0004 / 0008 の実測）が、
-- ここは DEFAULT が無く、既存の行は NULL で、NULL は CHECK を満たす（IS NULL の枝）。
--
-- ============================================================================
-- 完全に消す操作は、この列を見る
-- ============================================================================
--
-- DELETE /admin/characters/{handle} は「会話が無い」または「この列が NULL でない」行だけを消す。
-- 判定と削除は1つの DELETE 文（src/store/character.rs の DELETE_CHARACTER）。
-- キャラクターを指す表はどれも ON DELETE CASCADE なので、中身ごと消える（控えは残さない）。

ALTER TABLE character ADD COLUMN archived_at TEXT
    CHECK (archived_at IS NULL OR typeof(archived_at) = 'text');
