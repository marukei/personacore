-- 性格ステータスの変容の「累積」を置くテーブル
-- （ADR-0027 §決定1〜3・§決定7 / 作業単位 16e-b）。
--
-- ============================================================================
-- 設計はここに書かない
-- ============================================================================
--
-- 「何が入るか」「なぜ票の表と別なのか」「1行壊れたときに何が止まるか」は
-- docs/03-data-model.md の stat_drift_charge の節が正。
--
-- **適用済みのマイグレーションは二度と編集できない**（sqlx のチェックサム）ので、
-- ここに設計判断を写すと、判断が変わった日に古い写しが永久に残る。
-- 残すのは「この SQL を読むときにだけ要る注意」だけにする。
--
-- ============================================================================
-- 名前に mem+ory を含めない / 票の表の名前を含めない
-- ============================================================================
--
-- 記憶の SQL 走査テスト（src/store/memory.rs の no_statement_updates_or_deletes_a_memory）と
-- 票の SQL 走査テスト（src/store/drift.rs の no_statement_updates_or_deletes_a_vote）は
-- **どちらもテーブル名の文字列**で migrations/** を走査する。
-- その名前を含むテーブルを作ると、そこへの UPDATE が誤検出される。0009 / 0010 と同じ注意。
--
-- ============================================================================
-- この表は「書き換わる」表である（票の表とは立場が逆）
-- ============================================================================
--
-- 票は追記のみで、走査が UPDATE / DELETE を禁じている。
-- こちらは**1軸につき1行の現在値**で、毎ターン上書きされる。
-- 履歴が要る用途（何がいつ動いたか）は票とログの側が持つ。
--
-- ============================================================================
-- axis の CHECK が3条件ある理由（0009 が実測した穴 / 0010 の写し）
-- ============================================================================
--
-- * 空白のみを弾く条件は stat_alloc.axis の写し（0001）。半角スペースだけでは足りない。
-- * typeof を縛るのは型アフィニティ対策。BLOB は TEXT へ変換されないので、
--   縛らないと「読み出しでだけ落ちる行」が作れる。
-- * SQLite の length() は**テキストを最初の NUL までしか数えない**ので、
--   NUL そのものを instr で見る必要がある。
--
-- charge の typeof を 'real' に縛るのも同じ理由。'1.5' という TEXT の行を作られると、
-- 読み出しでだけ落ちる（そして落ちた回は、そのキャラクターの変容が丸ごと止まる）。
CREATE TABLE stat_drift_charge (
    character_id INTEGER NOT NULL REFERENCES character(id) ON DELETE CASCADE,
    axis TEXT NOT NULL CHECK (
        typeof(axis) = 'text'
        AND instr(axis, char(0)) = 0
        AND length(trim(
            axis,
            ' ' || char(9) || char(10) || char(11) || char(12) || char(13) || char(12288) || char(160)
        )) > 0
    ),
    charge REAL NOT NULL DEFAULT 0.0 CHECK (typeof(charge) = 'real'),
    updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    PRIMARY KEY (character_id, axis)
);
